/* Pan & Zoom State */
let scale = 1, tx = 0, ty = 0;
let dragging = false, moved = false, sx = 0, sy = 0;

function applyTransform() {
  vp.setAttribute("transform", "translate(" + tx + "," + ty + ") scale(" + scale + ")");
}

/* Fit whole graph within viewport */
function fitGraph() {
  if (!svg || !gw) return;
  const vb = svg.getAttribute("viewBox");
  if (!vb) return;
  const parts = vb.split(" ").map(Number);
  const w = parts[2] || 800;
  const h = parts[3] || 600;
  const gwW = gw.clientWidth || 800;
  const gwH = gw.clientHeight || 560;

  const k = Math.min(gwW / w, gwH / h, 1);
  scale = Math.max(0.04, k * 0.95);
  tx = (gwW - w * scale) / 2;
  ty = 16;
  applyTransform();
}

/* Focus and center viewport on a specific node */
function focusNode(id) {
  if (!svg || !gw || !id) return;
  const nodeEl = nodeLayer.querySelector('[data-id="' + CSS.escape(id) + '"]');
  if (!nodeEl) return;

  const tf = nodeEl.getAttribute("transform");
  if (!tf) return;
  const m = tf.match(/translate\(([^,]+),\s*([^)]+)\)/);
  if (!m) return;
  const nx = parseFloat(m[1]);
  const ny = parseFloat(m[2]);

  const rect = nodeEl.querySelector("rect");
  const nw = rect ? parseFloat(rect.getAttribute("width") || "200") : 200;
  const nh = rect ? parseFloat(rect.getAttribute("height") || "26") : 26;

  const gwW = gw.clientWidth || 800;
  const gwH = gw.clientHeight || 560;

  /* Keep current user scale if already readable (>= 0.75), else zoom in to 1.0 */
  if (scale < 0.75) {
    scale = 1.0;
  }
  tx = gwW / 2 - (nx + nw / 2) * scale;
  ty = gwH / 2 - (ny + nh / 2) * scale;
  applyTransform();
}

/* On resize/fullscreen transition, preserve selected focus or re-center */
function onViewportResize(oldW, oldH) {
  if (selectedId && nodeLayer.querySelector('[data-id="' + CSS.escape(selectedId) + '"]')) {
    focusNode(selectedId);
  } else if (oldW && oldH && gw.clientWidth && gw.clientHeight) {
    /* Scale tx/ty to track center shift without shrinking scale */
    const dw = (gw.clientWidth - oldW) / 2;
    const dh = (gw.clientHeight - oldH) / 2;
    tx += dw;
    ty += dh;
    applyTransform();
  } else {
    fitGraph();
  }
}
gw.addEventListener("wheel", (e) => {
  e.preventDefault();
  const r = gw.getBoundingClientRect();
  const mx = e.clientX - r.left, my = e.clientY - r.top;
  const k = e.deltaY < 0 ? 1.14 : 1 / 1.14;
  const ns = Math.min(4, Math.max(0.04, scale * k));
  tx = mx - (mx - tx) * (ns / scale);
  ty = my - (my - ty) * (ns / scale);
  scale = ns;
  applyTransform();
}, { passive: false });

