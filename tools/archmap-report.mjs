/* String escape helper for dynamic HTML */
function escHtml(str) {
  return String(str ?? "").replace(/[&<>"']/g, (c) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
  }[c]));
}

/* Switch Graph Mode */
function setMode(mode) {
  if (currentMode === mode && nodeLayer.children.length > 0) return;
  currentMode = mode;
  tabModules.classList.toggle("active", mode === "modules");
  tabModules.setAttribute("aria-selected", mode === "modules");
  tabCalls.classList.toggle("active", mode === "calls");
  tabCalls.setAttribute("aria-selected", mode === "calls");

  if (mode === "modules") {
    if (btnConnectedFilter) btnConnectedFilter.style.display = "none";
    renderModulesMode();
  } else {
    if (btnConnectedFilter) {
      btnConnectedFilter.style.display = "inline-block";
      btnConnectedFilter.textContent = callsFilterConnectedOnly ? "Все символы" : "Только связанные";
    }
    renderCallsMode();
  }
  closePanel();
  fitGraph();
}

