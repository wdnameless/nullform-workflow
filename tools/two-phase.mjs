/**
 * tools/two-phase.mjs — two-phase execution for destructive edits.
 *
 * planDestructive(edit) returns { planToken, hash } binding the edit hash.
 * executeDestructive(planToken, edit, apply) executes apply(edit) only on verified plans
 * and invalidates the token (single-use). Unknown or mismatched tokens are refused.
 */
import { createHash, randomBytes } from 'node:crypto';

function canonicalize(val) {
  if (val === null || typeof val !== 'object') {
    return val;
  }
  if (Array.isArray(val)) {
    return val.map(canonicalize);
  }
  const sorted = {};
  for (const key of Object.keys(val).sort()) {
    sorted[key] = canonicalize(val[key]);
  }
  return sorted;
}

export function canonicalJson(val) {
  return JSON.stringify(canonicalize(val));
}

export function hashEdit(edit) {
  return createHash('sha256').update(canonicalJson(edit)).digest('hex');
}

const tokenRegistry = new Map();

/**
 * Plans a destructive edit and returns a plan token binding the edit hash.
 *
 * @param {unknown} edit - The edit specification or payload.
 * @returns {{ planToken: string, hash: string }}
 */
export function planDestructive(edit) {
  if (edit === undefined) {
    throw new Error('Edit payload is required for planDestructive');
  }
  const hash = hashEdit(edit);
  const planToken = randomBytes(16).toString('hex');
  tokenRegistry.set(planToken, hash);
  return { planToken, hash };
}

/**
 * Executes a planned destructive edit with verified token binding.
 *
 * @param {string} planToken - The token generated by planDestructive.
 * @param {unknown} edit - The edit payload matching the planned edit.
 * @param {(edit: unknown) => unknown} apply - Callback executing the edit.
 * @returns {unknown} Result of apply(edit).
 */
export function executeDestructive(planToken, edit, apply) {
  if (!planToken || !tokenRegistry.has(planToken)) {
    throw new Error(`Unknown plan token: "${planToken}"`);
  }
  const expectedHash = tokenRegistry.get(planToken);
  const actualHash = hashEdit(edit);
  if (expectedHash !== actualHash) {
    throw new Error(
      `Mismatched plan token for token "${planToken}": expected hash ${expectedHash}, got ${actualHash}`
    );
  }
  tokenRegistry.delete(planToken);
  if (typeof apply !== 'function') {
    throw new Error('Missing apply function in executeDestructive');
  }
  return apply(edit);
}

/**
 * Clears the in-memory plan token registry (useful in test isolation).
 */
export function clearPlanTokens() {
  tokenRegistry.clear();
}
